import { lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import MarkdownIt from 'markdown-it';

// A deliberately static site: Markdown is data, and only generated HTML/CSS is published.
const PAGE_MARKER = '<!-- Generated by gently-docs; do not edit. -->';
const CSS_MARKER = '/* Generated by gently-docs; do not edit. */';
const escape = text => String(text).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const defaults = fileURLToPath(new URL('.', import.meta.url));
const args = process.argv.slice(2);
let source = defaults;
let out = path.join(defaults, '..', '_site');
for (let index = 0; index < args.length; index += 2) {
  if (!['--source', '--out'].includes(args[index]) || !args[index + 1]) throw new Error('Usage: node build.mjs [--source DIRECTORY] [--out DIRECTORY]');
  if (args[index] === '--source') source = args[index + 1];
  else out = args[index + 1];
}
source = path.resolve(source);
out = path.resolve(out);

function stat(file) {
  try { return lstatSync(file); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}
function noSymlinks(file) {
  for (let current = file; ; current = path.dirname(current)) {
    if (stat(current)?.isSymbolicLink()) throw new Error(`Refusing symlink: ${current}`);
    if (current === path.dirname(current)) break;
  }
}
function contains(parent, child) {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}
function collect(dir, prefix = '') {
  const pages = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (['node_modules', '_book', '_site', '.git'].includes(entry.name)) continue;
    const name = prefix + entry.name;
    const file = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing source symlink: ${name}`);
    if (entry.isDirectory()) pages.push(...collect(file, `${name}/`));
    else if (entry.isFile() && /\.md$/i.test(entry.name)) pages.push(name);
    else if (!entry.isFile()) throw new Error(`Unsupported source file: ${name}`);
  }
  return pages;
}
function checkOutput(dir) {
  const info = stat(dir);
  if (!info) return;
  if (info.isSymbolicLink()) throw new Error(`Refusing output symlink: ${dir}`);
  if (!info.isDirectory()) throw new Error(`Unmanaged output: ${dir}`);
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing output symlink: ${file}`);
    if (entry.isDirectory()) checkOutput(file);
    else if (!entry.isFile() || !((entry.name.endsWith('.html') && readFileSync(file, 'utf8').startsWith(PAGE_MARKER))
      || (entry.name === 'site.css' && readFileSync(file, 'utf8').startsWith(CSS_MARKER)))) throw new Error(`Unmanaged output: ${file}`);
  }
}
function route(file) {
  return /(?:^|\/)README\.md$/i.test(file) ? file.replace(/README\.md$/i, 'index.html') : file.replace(/\.md$/i, '.html');
}

function build() {
  noSymlinks(source);
  noSymlinks(out);
  if (contains(source, out) || contains(out, source)) throw new Error('Source and output must not overlap');
  if (!stat(source)?.isDirectory()) throw new Error('Source must be a directory');
  checkOutput(out);
  const names = collect(source);
  if (!names.includes('README.md') || !names.includes('SUMMARY.md')) throw new Error('Source requires README.md and SUMMARY.md');
  const routes = new Map(names.filter(name => name !== 'SUMMARY.md').map(name => [name, route(name)]));
  if (new Set([...routes.values()].map(value => value.toLowerCase())).size !== routes.size) throw new Error('Markdown page routes collide');

  function link(href, current, fromRoute) {
    if (/^(?:https?:|mailto:)/i.test(href)) return href;
    if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//')) throw new Error(`Unsafe local link in ${current}`);
    const [, raw, suffix = ''] = href.match(/^([^?#]*)([?#].*)?$/);
    if (!raw) return href;
    let decoded;
    try { decoded = decodeURIComponent(raw); } catch { throw new Error(`Invalid local link in ${current}`); }
    if (decoded.startsWith('/') || /[\\\x00-\x1f\x7f]/.test(decoded)) throw new Error(`Local link outside docs in ${current}`);
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(current), decoded));
    if (target === '..' || target.startsWith('../')) throw new Error(`Local link outside docs in ${current}`);
    if (!/\.md$/i.test(target)) throw new Error(`Local link must target Markdown in ${current}`);
    if (!routes.has(target)) throw new Error(`Unknown local link target in ${current}: ${target}`);
    return path.posix.relative(path.posix.dirname(fromRoute), routes.get(target)).split('/').map(encodeURIComponent).join('/') + suffix;
  }

  const md = new MarkdownIt({ html: false, linkify: false, typographer: false });
  md.validateLink = href => !/[\x00-\x20\x7f]/.test(href) && !href.startsWith('//')
    && (!/^[a-z][a-z\d+.-]*:/i.test(href) || /^(?:https?:|mailto:)/i.test(href));
  md.renderer.rules.link_open = (tokens, index, options, env, renderer) => {
    tokens[index].attrSet('href', link(tokens[index].attrGet('href'), env.current, env.route));
    return renderer.renderToken(tokens, index, options);
  };
  // There are no documentation image assets. Do not introduce remote fetches or inline image data.
  md.renderer.rules.image = (tokens, index) => escape(tokens[index].content);

  const summary = readFileSync(path.join(source, 'SUMMARY.md'), 'utf8').split(/\r?\n/).filter(line => line.trim());
  const nav = summary.map(line => {
    if (line === '# Summary') return { type: 'skip' };
    const heading = line.match(/^## (.+)$/);
    if (heading) return { type: 'heading', label: heading[1] };
    const item = line.match(/^\* \[([^\]]+)\]\(([^)]+)\)$/);
    if (!item) throw new Error('Unsupported SUMMARY.md format');
    link(item[2], 'SUMMARY.md', 'index.html');
    return { type: 'link', label: item[1], href: item[2] };
  });
  const rendered = new Map();
  for (const [name, pageRoute] of routes) {
    const content = readFileSync(path.join(source, ...name.split('/')), 'utf8').replace(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/, '');
    const tokens = md.parse(content, {});
    let title = 'Gently documentation';
    const ids = new Map();
    for (let index = 0; index < tokens.length; index++) {
      if (tokens[index].type !== 'heading_open') continue;
      const text = (tokens[index + 1].children || []).map(token => token.content).join('');
      if (tokens[index].tag === 'h1' && title === 'Gently documentation') title = text;
      const slug = text.normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}_ -]/gu, '').trim().replace(/\s+/g, '-') || 'section';
      const count = ids.get(slug) || 0;
      ids.set(slug, count + 1);
      tokens[index].attrSet('id', slug + (count ? `-${count}` : ''));
    }
    const navigation = nav.map(item => item.type === 'heading' ? `<h2>${escape(item.label)}</h2>`
      : item.type === 'link' ? `<a href="${escape(link(item.href, 'SUMMARY.md', pageRoute))}">${escape(item.label)}</a>` : '').join('\n');
    const css = path.posix.relative(path.posix.dirname(pageRoute), 'site.css');
    rendered.set(pageRoute, `${PAGE_MARKER}\n<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'self'; base-uri 'none'; form-action 'none'"><title>${escape(title)} | Gently</title><link rel="stylesheet" href="${escape(css)}"></head><body><nav aria-label="Documentation">${navigation}</nav><main>${md.renderer.render(tokens, md.options, { current: name, route: pageRoute })}</main></body></html>\n`);
  }
  rendered.set('site.css', `${CSS_MARKER}\n:root{font:17px/1.6 system-ui,sans-serif;color:#202532;background:#fff}body{max-width:1200px;margin:auto;display:grid;grid-template-columns:240px minmax(0,1fr);gap:3rem;padding:2rem}nav{font-size:.9rem}nav a{display:block;margin:.35rem 0}nav h2{font-size:1rem;margin:1.3rem 0 .4rem}main{min-width:0}a{color:#215ab5}pre{overflow:auto;background:#f2f4f8;padding:1rem;border-radius:.4rem}code{font-family:ui-monospace,monospace;font-size:.9em}table{border-collapse:collapse;display:block;overflow:auto}th,td{padding:.5rem;border:1px solid #ccd2dc}blockquote{border-left:3px solid #ccd2dc;margin-left:0;padding-left:1rem}@media(max-width:750px){body{display:block;padding:1rem}nav{margin-bottom:2rem}}\n`);
  mkdirSync(path.dirname(out), { recursive: true });
  const staging = mkdtempSync(path.join(path.dirname(out), '.gently-docs-'));
  try {
    for (const [name, contents] of rendered) {
      const file = path.join(staging, ...name.split('/'));
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, contents, { flag: 'wx' });
    }
    // Recheck before replacing: a failed render never disturbs a previous successful build.
    noSymlinks(out);
    checkOutput(out);
    rmSync(out, { recursive: true, force: true });
    renameSync(staging, out);
  } finally { rmSync(staging, { recursive: true, force: true }); }
  console.log(`Built ${routes.size} documentation pages in ${out}`);
}

try { build(); } catch (error) { console.error(`Documentation build failed: ${error.message}`); process.exitCode = 1; }
